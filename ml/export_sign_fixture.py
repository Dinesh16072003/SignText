"""Writes the saved test samples that the browser model test compares against.

Run from the ml/ folder with:

    .venv/Scripts/python export_sign_fixture.py

It takes the first held-out test row of a handful of classes, asks the
SavedModel what it predicts for each one, and writes

    frontend/src/data/signFixture.json

for frontend/src/services/signModel.test.js. That test runs the TensorFlow.js
graph model on the same numbers and checks that both sides name the same
class, which is the browser half of the Part 6E parity check.

Nothing here trains, changes or re-exports the model. The features are only
rounded when they are written to JSON: six decimal places is far below the
smallest difference the model reacts to, and it keeps the file small.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import numpy as np
import tensorflow as tf

ML_DIR = Path(__file__).resolve().parent
ROOT_DIR = ML_DIR.parent
FEATURES_PATH = ML_DIR / "features" / "asl_features.npz"
CLASSES_PATH = ML_DIR / "features" / "classes.txt"
SPLIT_PATH = ML_DIR / "checkpoints" / "split_indices.npz"
EXPORT_DIR = ML_DIR / "checkpoints" / "alphabet_savedmodel"
OUT_PATH = ROOT_DIR / "frontend" / "src" / "data" / "signFixture.json"

# One sample from each of these classes, in this order. The set covers plain
# letters, the classes the model finds harder, and the two special classes
# that never print their own name.
WANTED = ["A", "C", "F", "I", "M", "Q", "T", "X", "space", "del"]
DECIMALS = 6


def main() -> None:
    classes = [line.strip() for line in open(CLASSES_PATH, encoding="utf-8") if line.strip()]
    features = np.asarray(np.load(FEATURES_PATH)["features"], dtype=np.float32)
    labels = np.asarray(np.load(FEATURES_PATH)["labels"], dtype=np.int64)
    test_idx = np.load(SPLIT_PATH)["test"]

    model = tf.saved_model.load(str(EXPORT_DIR))
    serve = model.signatures["serving_default"] if "serving_default" in model.signatures else model.signatures[next(iter(model.signatures))]

    samples = []
    for name in WANTED:
        label = classes.index(name)
        rows = test_idx[labels[test_idx] == label]
        if len(rows) == 0:
            raise RuntimeError(f"No test row for class {name!r}")
        row = int(rows[0])

        probs = serve(tf.constant(features[row : row + 1]))
        probs = probs[next(iter(probs))].numpy()[0]
        predicted = classes[int(probs.argmax())]
        margin = float(np.sort(probs)[-1] - np.sort(probs)[-2])

        samples.append(
            {
                "expected": predicted,
                "sourceRow": row,
                "confidence": round(float(probs.max()), 6),
                "margin": round(margin, 6),
                "features": [round(float(value), DECIMALS) for value in features[row]],
            }
        )
        print(
            f"{name:<6} row {row:>5}  SavedModel says {predicted:<6} "
            f"p={probs.max():.4f}  margin={margin:.4f}"
        )

    fixture = {
        "note": (
            "Saved hand feature vectors from the Step 5 test split "
            "(ml/features/asl_features.npz) with the predictions the "
            "TensorFlow SavedModel in ml/checkpoints/alphabet_savedmodel "
            "makes for them. Generated by ml/export_sign_fixture.py. The "
            "browser test runs the TensorFlow.js graph model on these same "
            "numbers and must name the same classes."
        ),
        "created": date.today().isoformat(),
        "seed": 12345,
        "split": "test",
        "model": "ml/checkpoints/alphabet_savedmodel",
        "featureLength": len(samples[0]["features"]),
        "classNames": classes,
        "samples": samples,
    }

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(f"\nWrote {len(samples)} samples to {OUT_PATH}")
    print(f"Size: {OUT_PATH.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
